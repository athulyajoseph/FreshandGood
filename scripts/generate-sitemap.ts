/**
 * Writes public/sitemap.xml and public/robots.txt from the seed data, using VITE_SITE_URL.
 * Runs automatically before `npm run build` (the "prebuild" script); run it by hand with
 * `npm run sitemap`. Needs Node 22.18+ (built-in TypeScript support).
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { categories } from '../src/data/categories.ts'
import { products } from '../src/data/products.ts'
import { DEFAULT_SITE_URL, resolveSiteUrl } from './siteUrl.ts'

type ChangeFreq = 'daily' | 'weekly' | 'monthly' | 'yearly'

interface SitemapEntry {
  path: string
  changefreq: ChangeFreq
  priority: number
}

const STATIC_ROUTES: SitemapEntry[] = [
  { path: '/', changefreq: 'weekly', priority: 1.0 },
  { path: '/products', changefreq: 'weekly', priority: 0.9 },
  { path: '/categories', changefreq: 'monthly', priority: 0.8 },
  { path: '/shops', changefreq: 'monthly', priority: 0.8 },
  { path: '/about', changefreq: 'yearly', priority: 0.5 },
  { path: '/contact', changefreq: 'yearly', priority: 0.5 },
]

const escapeXml = (value: string): string =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

function buildSitemap(siteUrl: string, entries: SitemapEntry[]): string {
  const lastmod = new Date().toISOString().slice(0, 10)
  const urls = entries
    .map(
      ({ path, changefreq, priority }) =>
        `  <url>\n    <loc>${escapeXml(siteUrl + path)}</loc>\n    <lastmod>${lastmod}</lastmod>\n    <changefreq>${changefreq}</changefreq>\n    <priority>${priority.toFixed(1)}</priority>\n  </url>`,
    )
    .join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`
}

function buildRobots(siteUrl: string): string {
  return `# Generated by scripts/generate-sitemap.ts\nUser-agent: *\nAllow: /\nDisallow: /search\n\nSitemap: ${siteUrl}/sitemap.xml\n`
}

const siteUrl = resolveSiteUrl(
  process.env.NODE_ENV === 'development' ? 'development' : 'production',
)
const entries: SitemapEntry[] = [
  ...STATIC_ROUTES,
  ...categories.map((c) => ({
    path: `/category/${c.slug}`,
    changefreq: 'weekly' as const,
    priority: 0.7,
  })),
  ...products.map((p) => ({
    path: `/product/${p.slug}`,
    changefreq: 'weekly' as const,
    priority: p.isFeatured ? 0.7 : 0.6,
  })),
]

const publicDir = new URL('../public/', import.meta.url)
writeFileSync(fileURLToPath(new URL('sitemap.xml', publicDir)), buildSitemap(siteUrl, entries))
writeFileSync(fileURLToPath(new URL('robots.txt', publicDir)), buildRobots(siteUrl))

console.log(
  `sitemap: wrote ${entries.length} URLs for ${siteUrl} to public/sitemap.xml and public/robots.txt`,
)
if (siteUrl === DEFAULT_SITE_URL) {
  console.warn(
    'sitemap: VITE_SITE_URL is not set, so the placeholder domain was used. Set it before deploying.',
  )
}
